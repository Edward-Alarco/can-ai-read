export function resolveLocale(acceptLanguage: string | null | undefined, preference?: string): Locale {
  if (preference === 'en' || preference === 'es') return preference;
  const preferred = (acceptLanguage || '').split(',').map((entry, index) => {
    const [tag, ...params] = entry.trim().split(';');
    const qParam = params.map(p => p.trim()).find(p => p.startsWith('q='));
    const quality = qParam ? Number(qParam.slice(2)) : 1;
    return { tag: tag.toLowerCase(), quality, index };
  }).filter(x => /^[a-z]{2,8}(-[a-z0-9]{1,8})*$/.test(x.tag) && Number.isFinite(x.quality) && x.quality > 0 && x.quality <= 1).sort((a,b) => b.quality - a.quality || a.index - b.index)[0];
  return preferred?.tag.split('-')[0] === 'es' ? 'es' : 'en';
}

export function translator(locale: Locale) {
  function t(input: string | TemplateStringsArray, ...values: unknown[]): string {
    const key = typeof input === 'string' ? input : input.reduce((s, part, i) => s + (i ? `{${i-1}}` : '') + part, '');
    const template = locale === 'es' ? key : translations[key] ?? key;
    return template.replace(/\{(\d+)\}/g, (_match, index) => String(values[Number(index)] ?? ''));
  }
  return t;
}
